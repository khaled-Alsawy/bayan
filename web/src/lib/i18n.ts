type StatusCopy = {
  label: string;
  detail: string;
  tone: "success" | "notice" | "danger";
};

export type Messages = (typeof messages)[UiLocale] & { locale: UiLocale };

export function isUiLocale(value: string | undefined): value is UiLocale {
  return value === "ar" || value === "en";
}

export function getMessages(locale: UiLocale): Messages {
  return { ...messages[locale], locale } as Messages;
}

export function localeDirection(locale: UiLocale): "rtl" | "ltr" {
  return locale === "ar" ? "rtl" : "ltr";
}

export function resolveResponseLocale(message: string, uiLocale: UiLocale): UiLocale {
  const normalized = message.trim();
  if (
    /\b(?:answer|respond|reply|write)(?:\s+to\s+me)?\s+in\s+arabic\b/i.test(normalized) ||
    /(?:أجب|اجب|جاوب|اكتب)(?:\s+لي)?(?:\s+باللغة)?\s+العربية/.test(normalized)
  ) {
    return "ar";
  }
  if (
    /\b(?:answer|respond|reply|write)(?:\s+to\s+me)?\s+in\s+english\b/i.test(normalized) ||
    /(?:أجب|اجب|جاوب|اكتب)(?:\s+لي)?(?:\s+باللغة)?\s+(?:الإنجليزية|الانجليزية)/.test(normalized)
  ) {
    return "en";
  }
  return uiLocale;
}
